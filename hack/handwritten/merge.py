"""Merge hand-written descriptors from hack/handwritten/types.yaml into
types.yaml, config/crds/, zz_generated.report.md and README.md.

krmgen.py makes a draft kind for every Terraform gap type its own kinds do
not cover, the types these hand-written kinds cover among them: such a
draft is dropped (its CRD in config/crds/drafts too), and the report's and
README's counts of covered types and drafts are made again."""
import json
import os
import re
import sys
import yaml

# The runtime's generator: the fieldRefs schema and required-field rules
# every generated kind has (RUNTIME, as hack/gen/generate.sh finds it).
sys.path.insert(0, os.path.join(os.environ.get("RUNTIME") or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "krm-rest-runtime"), "gen"))
import krmgen  # noqa: E402

HEAD = "# Code generated by krm-rest-runtime/gen/krmgen.py. DO NOT EDIT.\n"
HAND_HEAD = "# Generated from hack/handwritten/types.yaml by hack/handwritten/merge.py. DO NOT EDIT.\n"


def singular_of(kind):
    return kind.lower()


def build_crd(k, readiness):
    group = k["group"]
    kind = k["kind"]
    plural = k["plural"]
    version = k["version"]
    tf = ", ".join(k["terraform"])
    path = k["read"]["path"]

    props = dict(k.get("properties") or {})
    props["connectionRef"] = {
        "type": "object",
        "description": 'The Connection to use; default "default" in the same namespace.',
        "properties": {"name": {"type": "string"}},
    }
    props["secretRefs"] = {
        "type": "object",
        "description": "Fill body fields from Secrets: {<field>: {name, key}}. Use for tokens, passwords and secret values.",
        "additionalProperties": {
            "type": "object",
            "required": ["name", "key"],
            "properties": {"name": {"type": "string"}, "key": {"type": "string"}},
        },
    }

    props["secretRefs"]["maxProperties"] = 64
    props["fieldRefs"] = krmgen.FIELD_REFS
    spec_schema = {"type": "object", "properties": props}
    # As the generated kinds: a required field may be filled from another
    # object (fieldRefs) or a Secret (secretRefs) instead, by a CEL rule.
    rules, required = krmgen.required_rules(list(k.get("required") or []), {p["field"] for p in k.get("params") or []}, props)
    if rules:
        spec_schema["x-kubernetes-validations"] = rules
    if required:
        spec_schema["required"] = required

    return {
        "apiVersion": "apiextensions.k8s.io/v1",
        "kind": "CustomResourceDefinition",
        "metadata": {
            "name": f"{plural}.{group}",
            "annotations": {
                "hfl.dev/terraform": tf,
                "hfl.dev/api-path": path,
                "hfl.dev/readiness": readiness,
            },
        },
        "spec": {
            "group": group,
            "scope": "Namespaced",
            "names": {
                "kind": kind,
                "listKind": f"{kind}List",
                "plural": plural,
                "singular": singular_of(kind),
                "categories": ["hfl", "sentry"],
            },
            "versions": [
                {
                    "name": version,
                    "served": True,
                    "storage": True,
                    "subresources": {"status": {}},
                    "additionalPrinterColumns": [
                        {"name": "Ready", "type": "string", "jsonPath": '.status.conditions[?(@.type=="Ready")].status'},
                        {"name": "Reason", "type": "string", "jsonPath": '.status.conditions[?(@.type=="Ready")].reason'},
                        {"name": "Age", "type": "date", "jsonPath": ".metadata.creationTimestamp"},
                    ],
                    "schema": {
                        "openAPIV3Schema": {
                            "type": "object",
                            "description": f"{kind}: {k['shape']} resource at {path}. Terraform equivalent: {tf}. Fields keep the API's own names.",
                            "properties": {
                                "apiVersion": {"type": "string"},
                                "kind": {"type": "string"},
                                "metadata": {"type": "object"},
                                "spec": spec_schema,
                                "status": {
                                    "type": "object",
                                    "x-kubernetes-preserve-unknown-fields": True,
                                    "properties": {
                                        "id": {"type": "string"},
                                        "appliedHash": {"type": "string"},
                                        "observedGeneration": {"type": "integer"},
                                        "atProvider": {"type": "object", "x-kubernetes-preserve-unknown-fields": True},
                                        "conditions": {
                                            "type": "array",
                                            "items": {"type": "object", "x-kubernetes-preserve-unknown-fields": True},
                                        },
                                    },
                                },
                            },
                            "required": ["spec"],
                        }
                    },
                }
            ],
        },
    }


def main():
    root = sys.argv[1]
    hand_path = os.path.join(root, "hack", "handwritten", "types.yaml")
    types_path = os.path.join(root, "types.yaml")
    records_path = os.path.join(root, "hack", "live", "records.json")
    crds_dir = os.path.join(root, "config", "crds")
    report_path = os.path.join(root, "zz_generated.report.md")

    hand = yaml.safe_load(open(hand_path))["kinds"]
    types = yaml.safe_load(open(types_path))
    records = json.load(open(records_path)) if os.path.exists(records_path) else {}

    # Drafts krmgen made for Terraform types a hand-written kind covers.
    hand_tf = {t for k in hand for t in k["terraform"]}
    dropped = [k for k in types["kinds"] if k.get("readiness") == "draft" and set(k["terraform"]) <= hand_tf]
    types["kinds"] = [k for k in types["kinds"] if not any(k is d for d in dropped)]
    drop_drafts(crds_dir, dropped)

    existing = {k["kind"] for k in types["kinds"]}
    added = []
    for raw in hand:
        k = dict(raw)
        props = k.pop("properties", None)
        req = k.pop("required", None)
        rec = records.get(f"{k['kind']}.{k['group']}") or {}
        readiness = "live" if rec.get("result") == "pass" else "fake"
        k["readiness"] = readiness
        if k["kind"] in existing:
            raise SystemExit(f"duplicate kind {k['kind']}")
        types["kinds"].append(k)
        added.append((k, readiness))

        crd_obj = build_crd({**k, "properties": props, "required": req}, readiness)
        crd_file = f"{k['group']}_{k['plural']}.yaml"
        with open(os.path.join(crds_dir, crd_file), "w") as f:
            f.write(HAND_HEAD + yaml.safe_dump(crd_obj, sort_keys=False))

    with open(types_path, "w") as f:
        f.write(HEAD + yaml.safe_dump(types, sort_keys=False))

    kust_path = os.path.join(crds_dir, "kustomization.yaml")
    crd_files = sorted(f for f in os.listdir(crds_dir) if f.endswith(".yaml") and f != "kustomization.yaml")
    with open(kust_path, "w") as f:
        f.write(HEAD + yaml.safe_dump({"resources": crd_files}, sort_keys=False))

    real = [k for k in types["kinds"] if k.get("readiness") != "draft"]
    drafts = [k for k in types["kinds"] if k.get("readiness") == "draft"]
    cfg = yaml.safe_load(open(os.path.join(root, "hack", "gen", "vendor.yaml")))
    tf = cfg["terraform"]
    gaps = json.load(open(os.path.join(root, "hack", "gen", tf["gaps"])))[tf["provider"]]["gaps"]
    hard = cfg.get("hardBlocks") or {}

    report = open(report_path).read()
    live_n = sum(1 for k in real if k.get("readiness") == "live")
    report = re.sub(r"^\d+ kinds,", f"{len(real)} kinds,", report, flags=re.M)
    report = re.sub(r"Readiness `live` \(\d+\):", f"Readiness `live` ({live_n}):", report)
    covered = len({t for k in real for t in k["terraform"]})
    report = re.sub(r"^Terraform gap types: .*$",
                    f"Terraform gap types: {covered} of {len(gaps)} covered by these kinds"
                    + (f"; {len(drafts)} drafts (below)" if drafts else "")
                    + (f"; {len(hard)} not built (vendor.yaml hardBlocks)" if hard else "") + ".",
                    report, count=1, flags=re.M)
    report = drop_report_drafts(report, dropped, len(drafts))
    extra_rows = []
    for k, readiness in added:
        tfs = ", ".join(f"`{t}`" for t in k["terraform"])
        extra_rows.append(f"| {k['kind']} | `{k['group']}` | {k['shape']} | `{k['read']['path']}` | {tfs} | {readiness} |")
    # The hand-written kinds' rows go at the end of the kinds table, before
    # any section after it (Drafts, Not built).
    lines = report.rstrip("\n").split("\n")
    end = lines.index("| Kind | API group | Shape | API path | Terraform | Readiness |") + 1
    while end < len(lines) and lines[end].startswith("| "):
        end += 1
    lines[end:end] = extra_rows
    with open(report_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    # README's generated "Not covered" part, now that the dropped drafts are covered.
    krmgen.DRAFT_INFO.update({"gaps": len(gaps), "hardBlocks": hard, "draftNotes": cfg.get("draftNotes") or {}})
    krmgen.write_readme(root, cfg, {"kinds": types["kinds"]})
    print(f"{cfg['vendor']}: with {len(added)} hand-written kinds: {len(real)} kinds, {covered} Terraform gap resources"
          + (f", {len(drafts)} drafts" if drafts else "")
          + (f" ({len(dropped)} drafts of types they cover dropped)" if dropped else ""), file=sys.stderr)


def drop_drafts(crds_dir, dropped):
    """Remove the dropped drafts' CRDs from config/crds/drafts, and the
    directory with its kustomization if none is left."""
    draft_dir = os.path.join(crds_dir, "drafts")
    if not dropped or not os.path.isdir(draft_dir):
        return
    for k in dropped:
        path = os.path.join(draft_dir, f"{k['group']}_{k['plural']}.yaml")
        if os.path.exists(path):
            os.remove(path)
    kust = os.path.join(draft_dir, "kustomization.yaml")
    left = sorted(f for f in os.listdir(draft_dir) if f.endswith(".yaml") and f != "kustomization.yaml")
    if not left:
        if os.path.exists(kust):
            os.remove(kust)
        if not os.listdir(draft_dir):
            os.rmdir(draft_dir)
        return
    text = open(kust).read()
    head = text[:text.index("apiVersion:")]
    doc = yaml.safe_load(text)
    doc["resources"] = left
    with open(kust, "w") as f:
        f.write(head + yaml.safe_dump(doc, sort_keys=False))


def drop_report_drafts(report, dropped, left):
    """The report without the dropped drafts' sections; without its Drafts
    section if no draft is left."""
    names = {f"### {k['kind']} (`{k['terraform'][0]}`)" for k in dropped}
    out, skipping = [], False
    for line in report.split("\n"):
        if line.startswith("## ") or line.startswith("### "):
            skipping = line in names or (left == 0 and line.startswith("## Drafts ("))
            if line.startswith("## Drafts (") and left:
                line = f"## Drafts ({left})"
        if not skipping:
            out.append(line)
    return "\n".join(out)


if __name__ == "__main__":
    main()
